import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { dirs, ensureDirs } from "../scripts/lib/paths.mjs";
import { buildIndex, projectEntries, readMemories } from "../scripts/lib/memory-index.mjs";

function setup() {
  const d = dirs(path.join(fs.mkdtempSync(path.join(os.tmpdir(), "peka-index-")), "peka"));
  ensureDirs(d);
  return d;
}

function memory(d, name, { type = "project", description = `about ${name}`, project } = {}) {
  const meta = [`metadata:`, `  type: ${type}`, ...(project ? [`  project: ${project}`] : [])];
  fs.writeFileSync(
    path.join(d.memory, `${name}.md`),
    ["---", `name: ${name}`, `description: ${description}`, ...meta, "---", "", "Body.", ""].join("\n"),
  );
}

const read = (d, rel) => fs.readFileSync(path.join(d.memory, rel), "utf8");

test("MEMORY.md lists global memories by type then name, and one line per project", () => {
  const d = setup();
  memory(d, "zeta-ref", { type: "reference" });
  memory(d, "beta-user", { type: "user" });
  memory(d, "alpha-feedback", { type: "feedback" });
  memory(d, "abq-deploy", { type: "feedback", project: "abqary-new" });
  memory(d, "abq-billing", { project: "abqary-new" });
  memory(d, "wajom-build", { type: "feedback", project: "wajom-portal, wajom-client" });
  buildIndex(d);
  const lines = read(d, "MEMORY.md").trimEnd().split("\n");
  assert.match(lines[0], /^<!-- Generated by PEKA from the memory files\. Edits here are overwritten\. -->$/);
  assert.deepEqual(lines.slice(1), [
    "- [alpha-feedback](alpha-feedback.md) — about alpha-feedback",
    "- [beta-user](beta-user.md) — about beta-user",
    "- [zeta-ref](zeta-ref.md) — about zeta-ref",
    "",
    "## Projects",
    "- abqary-new: 2 memories, see [projects/abqary-new.md](projects/abqary-new.md)",
    "- wajom-client: 1 memory, see [projects/wajom-client.md](projects/wajom-client.md)",
    "- wajom-portal: 1 memory, see [projects/wajom-portal.md](projects/wajom-portal.md)",
  ]);
});

test("a project sub-index links back to the memory files, multi-project memories in each", () => {
  const d = setup();
  memory(d, "abq-billing", { project: "abqary-new" });
  memory(d, "abq-deploy", { type: "feedback", project: "abqary-new" });
  memory(d, "wajom-build", { type: "feedback", project: "wajom-portal, wajom-client" });
  buildIndex(d);
  assert.equal(
    read(d, "projects/abqary-new.md"),
    [
      "<!-- Generated by PEKA from the memory files. Edits here are overwritten. -->",
      "# abqary-new",
      "",
      "- [abq-deploy](../abq-deploy.md) — about abq-deploy",
      "- [abq-billing](../abq-billing.md) — about abq-billing",
      "",
    ].join("\n"),
  );
  assert.match(read(d, "projects/wajom-portal.md"), /\[wajom-build\]\(\.\.\/wajom-build\.md\)/);
  assert.match(read(d, "projects/wajom-client.md"), /\[wajom-build\]\(\.\.\/wajom-build\.md\)/);
  assert.deepEqual(projectEntries(d, "abqary-new"), [
    "- [abq-deploy](abq-deploy.md) — about abq-deploy",
    "- [abq-billing](abq-billing.md) — about abq-billing",
  ]);
  assert.deepEqual(projectEntries(d, "nothing-here"), []);
  assert.deepEqual(projectEntries(d, null), []);
});

test("long descriptions are clipped to 150 characters", () => {
  const d = setup();
  memory(d, "long", { description: "x".repeat(400) });
  buildIndex(d);
  const line = read(d, "MEMORY.md").split("\n")[1];
  assert.equal(line, `- [long](long.md) — ${"x".repeat(149)}…`);
});

test("MEMORY.md stays within 190 lines and says how many global memories were left out", () => {
  const d = setup();
  for (let i = 0; i < 200; i++) memory(d, `m${String(i).padStart(3, "0")}`);
  memory(d, "p1", { project: "proj" });
  const r = buildIndex(d);
  const lines = read(d, "MEMORY.md").trimEnd().split("\n");
  assert.ok(lines.length <= 190, `${lines.length} lines`);
  assert.equal(r.overflow, 200 - (lines.length - 1 - 1 - 3));
  assert.ok(lines.includes(`- … ${r.overflow} more global memories, run /peka:status`));
  assert.ok(lines.includes("- proj: 1 memory, see [projects/proj.md](projects/proj.md)"));
});

test("sub-indexes of projects with no memories left are removed", () => {
  const d = setup();
  memory(d, "old", { project: "gone" });
  buildIndex(d);
  assert.ok(fs.existsSync(path.join(d.memory, "projects", "gone.md")));
  fs.rmSync(path.join(d.memory, "old.md"));
  buildIndex(d);
  assert.equal(fs.existsSync(path.join(d.memory, "projects", "gone.md")), false);
  assert.doesNotMatch(read(d, "MEMORY.md"), /## Projects/);
});

test("an unchanged store is not rewritten", () => {
  const d = setup();
  memory(d, "a");
  assert.equal(buildIndex(d).changed, true);
  const file = path.join(d.memory, "MEMORY.md");
  const old = new Date("2020-01-01");
  fs.utimesSync(file, old, old);
  assert.equal(buildIndex(d).changed, false);
  assert.equal(fs.statSync(file).mtime.getTime(), old.getTime());
});

test("a memory without frontmatter is listed as global under its file name", () => {
  const d = setup();
  fs.writeFileSync(path.join(d.memory, "loose.md"), "just text\n");
  fs.writeFileSync(path.join(d.memory, "bad.md"), "---\nname: bad\nmetadata:\n  project:\n---\n");
  buildIndex(d);
  const text = read(d, "MEMORY.md");
  assert.match(text, /^- \[loose\]\(loose\.md\) — \(no description\)$/m);
  assert.match(text, /^- \[bad\]\(bad\.md\) — \(no description\)$/m);
  assert.deepEqual(
    readMemories(d).map((m) => [m.file, m.projects]),
    [["bad.md", []], ["loose.md", []]],
  );
});

test("a hand edit of MEMORY.md is replaced and the old index is ignored as a memory", () => {
  const d = setup();
  memory(d, "a");
  fs.writeFileSync(path.join(d.memory, "MEMORY.md"), "- [Old title](a.md) — hand written\n");
  buildIndex(d);
  assert.match(read(d, "MEMORY.md"), /^- \[a\]\(a\.md\) — about a$/m);
  assert.doesNotMatch(read(d, "MEMORY.md"), /Old title/);
});

test("MEMORY.md stays under 24 KB so the project lines are never cut off at load", () => {
  const d = setup();
  for (let i = 0; i < 150; i++) memory(d, `memory-with-a-fairly-long-name-${String(i).padStart(3, "0")}`, { description: "d".repeat(200) });
  memory(d, "p1", { project: "proj" });
  const r = buildIndex(d);
  const text = read(d, "MEMORY.md");
  assert.ok(Buffer.byteLength(text) <= 24000, `${Buffer.byteLength(text)} bytes`);
  assert.ok(r.overflow > 0);
  assert.match(text, new RegExp(`- … ${r.overflow} more global memories, run /peka:status`));
  assert.match(text, /- proj: 1 memory, see \[projects\/proj\.md\]\(projects\/proj\.md\)\n$/);
});
