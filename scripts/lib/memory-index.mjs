import fs from "node:fs";
import path from "node:path";
import { projectsOf, readFrontmatter } from "./frontmatter.mjs";
import { log } from "./state.mjs";

// Claude Code loads roughly the first 200 lines of MEMORY.md; stay safely under that.
const MAX_LINES = 190;
const MAX_DESCRIPTION = 150;
const HEADER = "<!-- Generated by PEKA from the memory files. Edits here are overwritten. -->";
const TYPE_ORDER = ["feedback", "user", "project", "reference"];

export function readMemories(d) {
  let files = [];
  try {
    files = fs.readdirSync(d.memory).filter((f) => f.endsWith(".md") && f !== "MEMORY.md");
  } catch {
    return [];
  }
  return files.sort().map((file) => {
    let fields = {};
    try {
      fields = readFrontmatter(fs.readFileSync(path.join(d.memory, file), "utf8"));
    } catch {
      // Unreadable file: list it under its file name.
    }
    return {
      file,
      name: fields.name || file.slice(0, -3),
      description: fields.description || "",
      type: fields.type || "",
      projects: projectsOf(fields),
    };
  });
}

function rank(m) {
  const i = TYPE_ORDER.indexOf(m.type);
  return i === -1 ? TYPE_ORDER.length : i;
}

function sorted(memories) {
  return [...memories].sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name));
}

function entry(m, prefix = "") {
  const text = m.description.replace(/\s+/g, " ").trim() || "(no description)";
  const clipped = text.length > MAX_DESCRIPTION ? `${text.slice(0, MAX_DESCRIPTION - 1)}…` : text;
  return `- [${m.name}](${prefix}${m.file}) — ${clipped}`;
}

function byProject(memories) {
  const groups = new Map();
  for (const m of memories) {
    for (const p of m.projects) {
      if (!groups.has(p)) groups.set(p, []);
      groups.get(p).push(m);
    }
  }
  return new Map([...groups].sort(([a], [b]) => a.localeCompare(b)));
}

// Index lines for one project, linked relative to the memory dir (for the session brief).
export function projectEntries(d, project) {
  if (!project) return [];
  return sorted(readMemories(d).filter((m) => m.projects.includes(project))).map((m) => entry(m));
}

function writeIfChanged(file, text) {
  try {
    if (fs.readFileSync(file, "utf8") === text) return false;
  } catch {
    // Missing: write it.
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
  return true;
}

function render(memories) {
  const global = sorted(memories.filter((m) => m.projects.length === 0)).map((m) => entry(m));
  const groups = byProject(memories);
  const projectLines = [...groups].map(([p, list]) => {
    const count = `${list.length} ${list.length === 1 ? "memory" : "memories"}`;
    return `- ${p}: ${count}, see [projects/${p}.md](projects/${p}.md)`;
  });
  const tail = projectLines.length ? ["", "## Projects", ...projectLines] : [];
  const budget = MAX_LINES - 1 - tail.length;
  let overflow = 0;
  let kept = global;
  if (global.length > budget) {
    kept = global.slice(0, Math.max(budget - 1, 0));
    overflow = global.length - kept.length;
    kept.push(`- … ${overflow} more global memories, run /peka:status`);
  }
  return { text: `${[HEADER, ...kept, ...tail].join("\n")}\n`, groups, overflow };
}

// Rebuild MEMORY.md and memory/projects/<project>.md from the memory files. Never throws.
export function buildIndex(d) {
  try {
    const memories = readMemories(d);
    const { text, groups, overflow } = render(memories);
    let changed = writeIfChanged(path.join(d.memory, "MEMORY.md"), text);

    const projectsDir = path.join(d.memory, "projects");
    for (const [p, list] of groups) {
      const body = [HEADER, `# ${p}`, "", ...sorted(list).map((m) => entry(m, "../")), ""].join("\n");
      changed = writeIfChanged(path.join(projectsDir, `${p}.md`), body) || changed;
    }
    let existing = [];
    try {
      existing = fs.readdirSync(projectsDir);
    } catch {
      // No sub-indexes yet.
    }
    for (const name of existing) {
      if (name.endsWith(".md") && !groups.has(name.slice(0, -3))) {
        fs.rmSync(path.join(projectsDir, name), { force: true });
        changed = true;
      }
    }
    return { changed, overflow };
  } catch (err) {
    log(d, `memory index: ${err?.message ?? err}`);
    return { changed: false, overflow: 0 };
  }
}
